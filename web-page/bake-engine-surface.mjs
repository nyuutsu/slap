// Bakes the engine's surface into page/engine-surface.mjs, so the stage furniture renders before the reactor arrives.
// Run through `make web-bake-surface` after the surface changes;
// the census fails whenever the baked file and the engine disagree, so a stale bake cannot ship.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const [probePath] = process.argv.slice(2);
if (!probePath) throw new Error('usage: node bake-engine-surface.mjs PROBE-BINARY');

const envelope = JSON.parse(execFileSync(probePath, ['surface']).toString());
const engineSpokenSurface = envelope.envelopeAnswer.Right;

const moduleText = `// The engine's surface, spoken by the engine itself at bake time, so the stage furniture renders before the reactor arrives.
// Generated by bake-engine-surface.mjs (make web-bake-surface).
// Two guards: the census fails when this file and the engine disagree, and the page refuses to boot an engine speaking another surface.
export const engineSurface = ${JSON.stringify(engineSpokenSurface, null, 2)};
`;
writeFileSync(new URL('./page/engine-surface.mjs', import.meta.url), moduleText);
console.log('baked the engine surface into page/engine-surface.mjs');
