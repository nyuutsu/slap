// Bakes dist-web/sw.js: the service worker that precaches the page whole, one cache per build.
// A new deploy installs as a complete new cache before it takes over, so the page, the baked surface,
// and the reactor can never mix generations; the handover waits until every slap tab has closed.
// Run by assemble-web; the precache list is built here so it can never drift from the assembled tree.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const [distRoot, buildVersion] = process.argv.slice(2);
if (!distRoot || !buildVersion) throw new Error('usage: node bake-service-worker.mjs DIST-ROOT VERSION');

const filesUnder = (branch, keep) => readdirSync(join(distRoot, branch), { withFileTypes: true })
  .filter((entry) => entry.isFile() && keep(entry.name))
  .map((entry) => `/${branch}/${entry.name}`);

const precachePaths = [
  '/',
  '/style.css',
  '/manifest.json',
  '/vendor/lit-html/lit-html.js',
  ...filesUnder('page', () => true),
  ...filesUnder('page/verbs', () => true),
  ...filesUnder('reactor', (name) => !name.endsWith('.br') && !name.endsWith('.gz')),
  ...filesUnder('vendor/browser_wasi_shim/dist', (name) => name.endsWith('.js')),
  ...filesUnder('fonts', (name) => name.endsWith('.woff2')),
  ...filesUnder('art', (name) => name.endsWith('.svg') || name.endsWith('.png') || name.endsWith('.webp')),
].sort();

// The cache is keyed by content, not by commit alone: trial deploys share one "-dirty" describe,
// and a key that failed to change would leave every installed browser serving the previous deploy.
const contentDigest = createHash('sha256');
for (const path of precachePaths)
  contentDigest.update(readFileSync(join(distRoot, path === '/' ? 'index.html' : path.slice(1))));
const buildKey = `${buildVersion} ${contentDigest.digest('hex').slice(0, 12)}`;

const workerText = `// slap's service worker, generated by bake-service-worker.mjs at assembly.
// One cache per build: install fetches the whole page into it, activate drops every older one,
// and fetches answer from this build's cache alone — a deploy can never mix generations.
// The browser re-reads this file on later visits (it rides the no-cache header). A changed build
// waits for every slap tab to close before taking over, unless a page asks for it sooner: the
// take-the-newer-page message is the fellow's "take it" button, and skipWaiting answers it.

const BUILD_CACHE = ${JSON.stringify(`slap ${buildKey}`)};
const PRECACHE_PATHS = ${JSON.stringify(precachePaths, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(BUILD_CACHE).then((cache) => cache.addAll(PRECACHE_PATHS)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then((names) => Promise.all(names.filter((name) => name !== BUILD_CACHE).map((name) => caches.delete(name))))
    .then(() => self.clients.claim()));
});

self.addEventListener('message', (event) => {
  if (event.data === 'take-the-newer-page') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET' || !event.request.url.startsWith(self.location.origin)) return;
  const sought = event.request.mode === 'navigate' ? '/' : event.request;
  event.respondWith(caches.open(BUILD_CACHE)
    .then((cache) => cache.match(sought, { ignoreVary: true }))
    .then((held) => held ?? fetch(event.request)));
});
`;

writeFileSync(join(distRoot, 'sw.js'), workerText);
console.log(`baked sw.js: ${precachePaths.length} paths precached for ${buildKey}`);
